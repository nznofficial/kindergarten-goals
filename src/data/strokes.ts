export const glyphs: Record<string, Glyph> = { ...upper, ...lower, ...digits }

export function glyphFor(ch: string): Glyph | null {
  return glyphs[ch] ?? null
}

/** True if every character can be traced — guards against a name with an accent. */
export function isTraceable(text: string): boolean {
  return [...text].every((c) => c === ' ' || c in glyphs)
}
