/**
 * Stroke centerlines for guided tracing, hand-authored in standard manuscript
 * form. These are the paths a child's finger follows, NOT letter outlines — a
 * font can't provide them, because what matters here is stroke order and
 * direction, which is exactly what kindergarten handwriting is graded on.
 *
 * Coordinate box is 100 x 140:
 *   y=22  ascender / capital top
 *   y=60  x-height top
 *   y=110 baseline
 *   y=138 descender bottom
 *
 * Each glyph is an ordered list of strokes; each stroke an ordered list of
 * points. Strokes must be traced in the order given, and each stroke from its
 * first point to its last.
 */
export type Point = [number, number]
export type Glyph = Point[][]

